import test from 'node:test'
import assert from 'node:assert/strict'
import { access, mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { createServer } from 'vite'

function fixture(turns = 40, timed = true) {
  const rows = [{ type: 'session', id: 'interaction-fixture', cwd: '/workspace/parity' }]
  let parentId = null
  const add = (id, message) => {
    rows.push({ type: 'message', id, parentId, ...(timed ? { timestamp: new Date(1700000000000 + rows.length * 1000).toISOString() } : {}), message })
    parentId = id
  }
  for (let i = 1; i <= turns; i++) {
    add(`u${i}`, { role: 'user', content: [{ type: 'text', text: `Question ${i}` }] })
    add(`a${i}`, { role: 'assistant', content: [{ type: 'thinking', thinking: `Reasoning ${i}` }, { type: 'text', text: `Answer ${i}` }, { type: 'toolCall', id: `call-${i}`, name: 'bash', arguments: { command: `echo keyword-${i}` } }], usage: { input: 0, output: i, cacheRead: 0 } })
    add(`r${i}`, { role: 'toolResult', toolCallId: `call-${i}`, toolName: 'bash', content: [{ type: 'text', text: `Result ${i}` }] })
  }
  return { name: 'interaction.jsonl', mimeType: 'application/jsonl', buffer: Buffer.from(rows.map(row => JSON.stringify(row)).join('\n')) }
}

async function executable() {
  for (const file of [process.env.CHROME_BIN, '/usr/bin/google-chrome', '/usr/bin/chromium', chromium.executablePath()].filter(Boolean)) {
    try { await access(file); return file } catch { /* Try the next installed browser. */ }
  }
}

test('full application timeline, ledger, detail and responsive interactions', { timeout: 120000 }, async t => {
  const executablePath = await executable()
  if (!executablePath) return t.skip('Install Chrome or run npx playwright install chromium to run browser acceptance.')
  const server = await createServer({ server: { host: '127.0.0.1', port: 15177, hmr: false, ws: false } })
  await server.listen()
  const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const screenshots = '.pi/acceptance'
  await mkdir(screenshots, { recursive: true })
  const load = async (count = 40, timed = true) => {
    await page.locator('input[type=file]').setInputFiles(fixture(count, timed))
    await page.locator('.record-table [data-kind]').first().waitFor()
    if (await page.getByLabel('Use recorded duration').getAttribute('aria-pressed') === 'true') await page.getByLabel('Use recorded duration').click()
  }
  const track = page.locator('.timeline-track')
  const drag = async (from, to, button = 'left') => {
    const box = await track.boundingBox()
    await page.mouse.move(box.x + box.width * from, box.y + 47)
    await page.mouse.down({ button })
    await page.mouse.move(box.x + box.width * to, box.y + 47, { steps: 12 })
    await page.mouse.up({ button })
  }
  const domain = () => track.evaluate(el => [Number(el.dataset.viewportStart), Number(el.dataset.viewportEnd)])
  const status = () => page.locator('.ledger-heading [role=status]').innerText()
  const clear = () => page.getByRole('button', { name: 'Clear timeline selection' }).click()
  try {
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`)
    await load()
    await t.test('forward/reverse range, context dimming, clear and scroll to unmounted records', async () => {
      await drag(.62, .79)
      assert.match(await status(), /21 in range/)
      assert.ok(await page.locator('tr[data-timeline-focus=true]').count() > 0)
      assert.ok(await page.locator('tr[data-timeline-focus=false]').count() > 0)
      assert.ok(await page.locator('.record-list').evaluate(el => el.scrollTop) > 1000)
      assert.equal(await page.evaluate(() => document.activeElement?.dataset.timelineFocus), 'true')
      const forward = await page.locator('[data-timeline-record-index][data-selected=true]').evaluateAll(els => els.map(el => el.dataset.timelineRecordIndex))
      await page.screenshot({ path: `${screenshots}/range-desktop.png`, fullPage: true })
      await clear()
      await drag(.79, .62)
      assert.deepEqual(await page.locator('[data-timeline-record-index][data-selected=true]').evaluateAll(els => els.map(el => el.dataset.timelineRecordIndex)), forward)
      await track.focus()
      await page.keyboard.press('Escape')
      assert.doesNotMatch(await status(), /in range/)
      assert.equal(await page.locator('[data-timeline-focus]').count(), 0)
    })
    await t.test('folded Turns/Calls, multiword search and timeline range compose', async () => {
      await page.getByLabel('Collapse all turns', { exact: true }).click()
      await page.getByLabel('Collapse all tool calls', { exact: true }).click()
      assert.equal(await page.getByLabel('Collapse all turns', { exact: true }).getAttribute('aria-pressed'), 'false')
      assert.equal(await page.locator('tr[data-kind=tool]').count(), 0)
      await drag(.25, .4)
      assert.ok(await page.locator('tr[data-kind=tool][data-timeline-focus=true]').count() > 0)
      await page.getByRole('searchbox').focus()
      await page.keyboard.type('result keyword-12', { delay: 15 })
      assert.equal(await page.getByRole('searchbox').inputValue(), 'result keyword-12')
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Search trajectory')
      assert.equal(await page.locator('tr[data-kind]').count(), 1)
      assert.match(await status(), /1 matches · 1 in range/)
      await clear()
      await page.getByLabel('Clear search', { exact: true }).click()
      assert.equal(await page.locator('tr[data-kind=tool]').count(), 0)
      await page.locator('[data-timeline-record-id="call-35"]').click()
      assert.match(await page.locator('.record-details').innerText(), /call-35/)
      assert.equal(await page.locator('tr[data-record-id="call-35"]').count(), 1)
      await page.getByLabel('Close details').click()
      await load()
    })
    await t.test('wheel zoom, right-drag pan, edge pan, Home reset and pointer cancellation', async () => {
      const box = await track.boundingBox()
      await page.mouse.move(box.x + box.width / 2, box.y + 46)
      await page.mouse.wheel(0, -700)
      await page.waitForFunction(() => Number(document.querySelector('.timeline-track').dataset.viewportEnd) - Number(document.querySelector('.timeline-track').dataset.viewportStart) < 120)
      const zoomed = await domain()
      await drag(.6, .4, 'right')
      assert.ok((await domain())[0] > zoomed[0])
      const beforeEdge = (await domain())[0]
      await drag(.5, .999)
      assert.ok((await domain())[0] > beforeEdge)
      await page.mouse.click(box.x + box.width / 2, box.y + 46, { button: 'right' })
      assert.doesNotMatch(await status(), /in range/)
      await track.focus(); await page.keyboard.press('Home')
      assert.deepEqual(await domain(), [0, 120])
      await page.mouse.move(box.x + box.width * .2, box.y + 46)
      await page.mouse.down(); await page.mouse.move(box.x + box.width * .5, box.y + 46)
      await track.dispatchEvent('pointercancel', { pointerId: 1 })
      await page.mouse.up()
      assert.doesNotMatch(await status(), /in range/)
      await page.mouse.click(box.x + box.width * .7, box.y + 47)
      assert.match(await status(), /in range/)
      await track.dblclick({ position: { x: 30, y: 47 } })
      assert.doesNotMatch(await status(), /in range/)
    })
    await t.test('keyboard block selection, detail resize, tabs and related-record navigation', async () => {
      await page.locator('[data-timeline-record-id="a20"]').focus()
      await page.keyboard.press('Enter')
      await page.locator('.record-details').waitFor()
      assert.match(await page.locator('.record-details').innerText(), /Reasoning 20/)
      await page.getByRole('button', { name: 'Thinking', exact: true }).click()
      assert.doesNotMatch(await page.locator('.record-details').innerText(), /Reasoning 20/)
      await page.getByRole('tab', { name: 'Preview', exact: true }).click()
      assert.equal(await page.getByRole('button', { name: 'Thinking', exact: true }).getAttribute('aria-expanded'), 'false')
      await page.getByRole('tab', { name: 'Overview', exact: true }).click()
      const handle = page.getByRole('separator', { name: 'Resize details' })
      const width = await page.locator('.record-details').evaluate(el => el.clientWidth)
      await handle.focus(); await page.keyboard.press('ArrowLeft')
      assert.ok(await page.locator('.record-details').evaluate(el => el.clientWidth) > width)
      const box = await handle.boundingBox()
      await page.mouse.move(box.x + 2, box.y + 100); await page.mouse.down(); await page.mouse.move(box.x - 50, box.y + 100); await page.mouse.up()
      assert.ok(await page.locator('.record-details').evaluate(el => el.clientWidth) > width + 40)
      await handle.dblclick()
      await page.getByRole('tab', { name: 'Raw', exact: true }).click()
      await page.locator('[data-timeline-record-id="a21"]').click()
      assert.equal(await page.getByRole('tab', { name: 'Raw', exact: true }).getAttribute('aria-selected'), 'true')
      await page.getByRole('tab', { name: 'Overview', exact: true }).click()
      await page.locator('.detail-call-list button').click()
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Close details')
      assert.match(await page.locator('.record-details').innerText(), /call-21/)
      await page.locator('.detail-navigate').first().click()
      assert.match(await page.locator('.record-details').innerText(), /Answer 21/)
      await page.screenshot({ path: `${screenshots}/detail-desktop.png`, fullPage: true })
      await page.getByLabel('Close details').click()
      await page.waitForFunction(() => document.activeElement?.dataset.recordId === 'a21')
      assert.equal(await page.evaluate(() => document.activeElement?.dataset.recordId), 'a21')
      await page.locator('[data-timeline-record-id="u1"]').focus()
      await page.keyboard.press('ArrowRight')
      await page.waitForFunction(() => document.activeElement?.dataset.timelineRecordId === 'a1')
      assert.equal(await page.evaluate(() => document.activeElement?.dataset.timelineRecordId), 'a1')
      assert.equal(await page.locator('.timeline-track [data-timeline-record-index][tabindex="0"]').count(), 1)
      await page.keyboard.press('Enter')
      await page.locator('.record-details').waitFor()
      await page.getByRole('searchbox').focus()
      await page.keyboard.type('keyword-1', { delay: 15 })
      assert.equal(await page.getByRole('searchbox').inputValue(), 'keyword-1')
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Search trajectory')
      await page.getByLabel('Clear search', { exact: true }).click()
      if (await page.locator('.record-details').count()) await page.getByLabel('Close details').click()
    })
    await t.test('missing timing, duration preference and importing the same filename reset viewport', async () => {
      await load(3, false)
      await page.getByLabel('Use recorded duration').click()
      assert.equal(await track.innerText(), 'No timing data')
      await page.reload()
      await page.locator('input[type=file]').setInputFiles(fixture(40))
      assert.equal(await page.getByLabel('Use recorded duration').getAttribute('aria-pressed'), 'true')
      await page.getByLabel('Use recorded duration').click()
      await drag(.1, .4)
      await page.getByLabel('Use recorded duration').click()
      assert.doesNotMatch(await status(), /in range/)
      await load()
      const box = await track.boundingBox()
      await page.mouse.move(box.x + box.width / 2, box.y + 46); await page.mouse.wheel(0, -700)
      await load()
      assert.deepEqual(await domain(), [0, 120])
      const zero = fixture(3)
      zero.buffer = Buffer.from(zero.buffer.toString().replace(/2023-[^"]+/g, '2023-11-14T22:13:20.000Z'))
      await page.locator('input[type=file]').setInputFiles(zero)
      await page.getByLabel('Use recorded duration').click()
      await page.getByText('No elapsed duration · showing record order').waitFor()
      assert.deepEqual(await domain(), [0, 9])
      await drag(.2, .6)
      assert.match(await status(), /5 in range/)
      await load()
    })
    await t.test('320–1440px layout, mobile details and touch range selection', async () => {
      for (const width of [320, 390, 768, 1024, 1440]) {
        await page.setViewportSize({ width, height: 844 })
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `page overflow at ${width}`)
        await page.locator('[data-timeline-record-id="a1"]').focus(); await page.keyboard.press('Enter')
        const box = await page.locator('.record-details').boundingBox()
        assert.ok(box.x >= 0 && box.x + box.width <= width, `details overflow at ${width}`)
        if (width === 390) await page.screenshot({ path: `${screenshots}/detail-mobile.png`, fullPage: true })
        await page.getByLabel('Close details').click()
      }
      await page.setViewportSize({ width: 390, height: 844 })
      const cdp = await page.context().newCDPSession(page)
      await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 })
      const box = await track.boundingBox()
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + box.width * .3, y: box.y + 46 }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: box.x + box.width * .6, y: box.y + 46 }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
      assert.match(await status(), /in range/)
      await page.screenshot({ path: `${screenshots}/range-mobile.png`, fullPage: true })
      await cdp.detach()
    })
    await t.test('over ten thousand records keep the ledger bounded and locate a distant tool', async () => {
      await page.setViewportSize({ width: 1440, height: 960 })
      await load(3400)
      assert.match(await status(), /10200 records/)
      assert.ok(await page.locator('.record-table tr').count() < 100)
      assert.equal(await page.locator('.timeline-track [data-timeline-record-index][tabindex="0"]').count(), 1)
      await drag(.9, .91)
      assert.ok(await page.locator('.record-list').evaluate(el => el.scrollTop) > 100000)
      assert.ok(await page.locator('tr[data-timeline-focus=true]').count() > 0)
      assert.ok(await page.locator('.record-table tr').count() < 100)
      await page.getByRole('searchbox').fill('call-3399')
      await page.locator('tr[data-kind=tool]').click()
      assert.match(await page.locator('.record-details').innerText(), /call-3399/)
    })
    assert.deepEqual(errors, [])
  } finally {
    await browser.close()
    await server.close()
  }
})
